"""Rebuild data/ from the published FEBRL 4 files: python get_data.py.

The files ship with the recordlinkage Python package (BSD 3 clause), which
redistributes the datasets generated by the FEBRL project (Christen 2008).
The synthetic social security style id column is dropped: the exercise is to
link the files without any shared identifier.
"""

from __future__ import annotations

import hashlib
import io
import urllib.request
from pathlib import Path

import pandas as pd

SOURCE = (
    "https://raw.githubusercontent.com/J535D165/recordlinkage/v0.16/"
    "recordlinkage/datasets/febrl/{name}.csv"
)
EXPECTED_SHA256 = {
    "dataset4a": "07c7cb3f0a8d88180e80317f2a60499dee4e8324a44c38059f4e7fed0a8b4488",
    "dataset4b": "2eed76c99fa2237be3ec013a123427926d4158abcb3a8f65874d6c7f1358cf2c",
}
OUTPUT_NAMES = {"dataset4a": "febrl4_a.csv", "dataset4b": "febrl4_b.csv"}
DROPPED_COLUMN = "soc_sec_id"
DATA = Path(__file__).resolve().parent / "data"


def download(name: str) -> bytes:
    """Fetch one raw file and check it is byte for byte the published version."""
    with urllib.request.urlopen(SOURCE.format(name=name), timeout=60) as response:
        raw = response.read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256[name]:
        raise ValueError(f"{name}: checksum {digest} does not match the published file")
    return raw


def main() -> None:
    DATA.mkdir(exist_ok=True)
    for name, output in OUTPUT_NAMES.items():
        frame = pd.read_csv(io.BytesIO(download(name)), dtype=str, skipinitialspace=True,
                            keep_default_na=False)
        frame.drop(columns=DROPPED_COLUMN).to_csv(DATA / output, index=False)
        print(f"wrote data/{output}: {len(frame):,} records")


if __name__ == "__main__":
    main()
